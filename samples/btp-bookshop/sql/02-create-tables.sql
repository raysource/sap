-- ============================================================
-- 02 建表（HANA 列式存储 CREATE COLUMN TABLE + 外键约束）
-- 顺序：先父表（GENRES / AUTHORS），再子表（BOOKS 引外键）
-- ============================================================

CREATE COLUMN TABLE BOOKSHOP.GENRES (
  ID    INT PRIMARY KEY,
  NAME  NVARCHAR(64)  NOT NULL,
  DESCR NVARCHAR(512)
);

CREATE COLUMN TABLE BOOKSHOP.AUTHORS (
  ID             INT PRIMARY KEY,
  NAME           NVARCHAR(128)  NOT NULL,
  DATE_OF_BIRTH  DATE,
  PLACE_OF_BIRTH NVARCHAR(128)
);

CREATE COLUMN TABLE BOOKSHOP.BOOKS (
  ID        INT PRIMARY KEY,
  TITLE     NVARCHAR(256) NOT NULL,
  DESCR     NVARCHAR(1024),
  AUTHOR_ID INT NOT NULL,
  GENRE_ID  INT NOT NULL,
  STOCK     INT DEFAULT 0,
  PRICE     DECIMAL(9,2),
  CURRENCY  NVARCHAR(3),
  CONSTRAINT FK_BOOKS_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES BOOKSHOP.AUTHORS (ID),
  CONSTRAINT FK_BOOKS_GENRE  FOREIGN KEY (GENRE_ID)  REFERENCES BOOKSHOP.GENRES  (ID)
);
